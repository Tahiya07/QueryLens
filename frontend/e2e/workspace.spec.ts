import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';

test('register, upload sample, profile and analyze revenue', async ({ page }) => {
  const email = `journey-${Date.now()}@example.com`;
  await page.goto('/');
  await page.getByRole('button', { name: 'New to QueryLens? Create an account' }).click();
  await page.getByPlaceholder('Work email').fill(email);
  await page.getByPlaceholder('Password (10+ characters)').fill('correct-horse-battery');
  await page.getByRole('button', { name: 'Create account' }).click();
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible();
  expect(await page.evaluate(() => sessionStorage.getItem('ql-token'))).toBeTruthy();
  expect(await page.evaluate(() => localStorage.getItem('ql-token'))).toBeNull();
  await page.getByLabel('Upload dataset').setInputFiles(path.resolve(__dirname, '../../sample-data/sales.csv'));
  await expect(page.getByRole('heading', { name: 'sales.csv' })).toBeVisible();
  await page.getByRole('button', { name: 'Find the highest value' }).click();
  await expect(page.getByText(/Calculated total revenue by product/)).toBeVisible();
  await expect(page.getByRole('cell', { name: 'Desk Lamp' }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Horizontal bars' }).click();
  await expect(page.getByRole('button', { name: 'Horizontal bars' })).toHaveAttribute('aria-pressed', 'true');
  const screenshots = path.resolve(__dirname, '../../screenshots');
  await fs.mkdir(screenshots, { recursive: true });
  await page.screenshot({ path: path.join(screenshots, 'analysis-workspace.png'), fullPage: true });
  await page.getByRole('button', { name: 'Query history' }).click();
  await expect(page.getByText('Which revenue is highest by product?').first()).toBeVisible();
  await page.getByRole('button', { name: 'Run again' }).click();
  await expect(page.getByText(/Calculated total revenue by product/)).toBeVisible();
  const question = page.getByPlaceholder('Ask a question about this dataset…');
  await question.fill('Show rows where region equals North');
  await page.getByRole('button', { name: 'Analyze' }).click();
  await expect(page.getByRole('cell', { name: 'North' })).toHaveCount(3);
  await question.fill('Sort rows by revenue ascending');
  await page.getByRole('button', { name: 'Analyze' }).click();
  await expect(page.getByRole('cell', { name: '300', exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Settings' }).click();
  await expect(page.getByText(/Signed in as/)).toBeVisible();
  await page.getByRole('button', { name: 'Documentation' }).click();
  await expect(page.getByRole('heading', { name: 'Using QueryLens' })).toBeVisible();
  await page.getByRole('button', { name: 'Overview' }).click();
  await expect(page.getByRole('heading', { name: 'Recent analysis activity' })).toBeVisible();
  await expect(page.getByText('Which revenue is highest by product?').first()).toBeVisible();
  await page.screenshot({ path: path.join(screenshots, 'overview-workspace.png'), fullPage: true });
});
